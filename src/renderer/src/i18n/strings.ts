/** Minimal lookup for dynamic keys (status- or kind-driven).
 * Static copy uses inline literals; this covers only keys chosen at runtime.
 * Plural base keys resolve via the `count` var (1 -> _one, else _other). */
export function tx(key: string, vars?: Record<string, string | number>): string {
  const count = vars?.['count']
  // Match i18next: when a count is passed and plural forms exist, 1 -> _one else _other.
  if (count !== undefined && EN[`${key}_other`] !== undefined)
    return fill(Number(count) === 1 ? (EN[`${key}_one`] ?? EN[`${key}_other`]) : EN[`${key}_other`], vars, count)
  const template = EN[key]
  if (template === undefined) return key
  return fill(template, vars, count)
}

function fill(template: string, vars: Record<string, string | number> | undefined, count: string | number | undefined): string {
  return template.replace(/\{\{(\w+)\}\}/g, (_, name: string) =>
    name === 'count' && count !== undefined ? String(count) : String(vars?.[name] ?? ''))
}
